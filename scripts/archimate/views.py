#!/usr/bin/env python3
"""Committed view images and their lock, docs/architecture/views/ (ADR 0009, step 4).

  python3 -I views.py --check  [ROOT]              compare model, lock and images; exit 1 naming
                                                   each view that is out of step (no Archi)
  python3 -I views.py --update ROOT REPORT         after an Archi build: take each view's PNG
                                                   from REPORT where the committed one is not
                                                   current, drop images of removed views, write
                                                   the lock
  python3 -I views.py --dims   ROOT REPORT         compare the dimensions of the PNGs in REPORT
                                                   with the lock (CI: bytes differ between
                                                   machines, dimensions must not)

ROOT is the repository (default: this script's): the model is ROOT/docs/architecture/model.xml,
the images and lock are in ROOT/docs/architecture/views/, the Archi version in
ROOT/tools/archi.env. REPORT is Archi's HTML report folder; it holds each view's PNG at
REPORT/<model identifier>/images/<view-id>.png.

`views.lock` has one line per view, sorted by view id:

    <view-id> <inputs-sha256> <png-sha256> <width>x<height>

The **rendering inputs** of a view (`rendering_inputs`) are everything in the model that changes
its picture and nothing else, written as one JSON text (keys sorted, compact, UTF-8) whose
sha256 is the lock's first hash:

* "archi": the pinned ARCHI_VERSION of tools/archi.env;
* "view": the view element in canonical form (exchange.serialize) without its `documentation`
  and `properties` (Archi does not draw them): identifier, type, viewpoint, name, every node with
  its coordinates and label, every connection with its bendpoints;
* "elements": [identifier, type, name] of each element a node draws, sorted;
* "relationships": [identifier, type, name, accessType, isDirected, modifier] of each
  relationship a connection draws, sorted ("" where an attribute is absent): the three attributes
  change a line's arrowheads or label.

So documentation and properties of anything, and other views, never change a view's hash.
Standard library only; the PNG size comes from the file's IHDR header.
"""

from __future__ import annotations

import copy
import hashlib
import json
import re
import shutil
import struct
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

# Sibling modules. Added explicitly because `python3 -I` (isolated mode) leaves the script's
# own folder off sys.path.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import exchange  # noqa: E402
import xsd_check  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
MODEL = Path("docs/architecture/model.xml")
VIEWS = Path("docs/architecture/views")
LOCK = "views.lock"
ENV = Path("tools/archi.env")
FIX = "run `just model` and commit `docs/architecture/views/`"
LOCK_HEADER = (
    "# Generated by `just model` (scripts/archimate/views.py, ADR 0009). Never edit by hand.\n"
    "# <view-id> <sha256 of the view's rendering inputs> <sha256 of the PNG> <width>x<height>\n"
    "# Rendering inputs: the Archi version, the view without documentation and properties, the\n"
    "# type and name of each element drawn, the type, name, accessType, isDirected and modifier\n"
    "# of each relationship drawn (exact definition: views.py, rendering_inputs).\n")
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
_LINE = re.compile(r"(\S+) ([0-9a-f]{64}) ([0-9a-f]{64}) ([1-9][0-9]*)x([1-9][0-9]*)")
_Q = f"{{{exchange.NS}}}"


class ViewsError(Exception):
    """A lock or PNG file that cannot be read."""


@dataclass(frozen=True)
class Entry:
    """One line of views.lock."""

    inputs: str
    png: str
    width: int
    height: int


# --- rendering inputs ---------------------------------------------------------------------------

def rendering_inputs(root: ET.Element, view: ET.Element, archi_version: str) -> bytes:
    """The bytes whose sha256 is the view's input hash (definition in the module docstring)."""
    drawn = copy.deepcopy(view)
    for tag in ("documentation", "properties"):
        for child in drawn.findall(f"{_Q}{tag}"):
            drawn.remove(child)
    refs = {n.get("elementRef") for n in view.iter(f"{_Q}node")} - {None}
    rel_refs = {c.get("relationshipRef") for c in view.iter(f"{_Q}connection")} - {None}
    elements = sorted([_ident(e), e.get(exchange.XSI_TYPE, ""), e.findtext(f"{_Q}name") or ""]
                      for e in root.iterfind(f"{_Q}elements/{_Q}element") if _ident(e) in refs)
    rels = sorted([_ident(r), r.get(exchange.XSI_TYPE, ""), r.findtext(f"{_Q}name") or "",
                   r.get("accessType", ""), r.get("isDirected", ""), r.get("modifier", "")]
                  for r in root.iterfind(f"{_Q}relationships/{_Q}relationship")
                  if _ident(r) in rel_refs)
    payload = {"archi": archi_version, "view": exchange.serialize(drawn),
               "elements": elements, "relationships": rels}
    return json.dumps(payload, sort_keys=True, ensure_ascii=False,
                      separators=(",", ":")).encode()


def input_hashes(model: bytes, archi_version: str) -> dict[str, str]:
    """View id -> sha256 of its rendering inputs. Raises exchange.FormatError on bad XML."""
    try:
        root = ET.fromstring(model)
    except ET.ParseError as err:
        raise exchange.FormatError([f"not well-formed XML: {err}"]) from None
    return {_ident(v): sha256(rendering_inputs(root, v, archi_version))
            for v in root.iterfind(f"{_Q}views/{_Q}diagrams/{_Q}view")}


def _ident(el: ET.Element) -> str:
    return el.get("identifier", "")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# --- PNG and lock -------------------------------------------------------------------------------

def png_size(data: bytes) -> tuple[int, int]:
    """(width, height) from a PNG's IHDR header. Raises ViewsError for anything else."""
    if data[:8] != PNG_SIGNATURE:
        raise ViewsError("not a PNG file (no PNG signature)")
    if len(data) < 24 or data[12:16] != b"IHDR":
        raise ViewsError("truncated PNG: no IHDR header")
    width, height = struct.unpack(">II", data[16:24])
    if not width or not height:
        raise ViewsError("PNG header gives a zero width or height")
    return width, height


def entry_for(inputs: str, png: bytes) -> Entry:
    width, height = png_size(png)
    return Entry(inputs, sha256(png), width, height)


def parse_lock(text: str) -> dict[str, Entry]:
    """Read views.lock. Raises ViewsError naming the first line that is not an entry."""
    entries: dict[str, Entry] = {}
    for n, line in enumerate(text.splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        m = _LINE.fullmatch(line)
        if not m:
            raise ViewsError(f"line {n} is not '<view-id> <sha256> <sha256> <width>x<height>'")
        if m[1] in entries:
            raise ViewsError(f"line {n}: view '{m[1]}' is listed twice")
        entries[m[1]] = Entry(m[2], m[3], int(m[4]), int(m[5]))
    return entries


def format_lock(entries: dict[str, Entry]) -> str:
    return LOCK_HEADER + "".join(f"{vid} {e.inputs} {e.png} {e.width}x{e.height}\n"
                                 for vid, e in sorted(entries.items()))


# --- check, update, dims ------------------------------------------------------------------------

def check(hashes: dict[str, str], lock: str | None, images: dict[str, bytes]) -> list[str]:
    """Problems between the model's input hashes, the lock text and the committed files.

    `images` maps each file name in the views folder other than the lock to its bytes.
    """
    if lock is None:
        return [f"{VIEWS / LOCK} is missing; {FIX}"]
    try:
        entries = parse_lock(lock)
    except ViewsError as err:
        return [f"{VIEWS / LOCK}: {err}; {FIX}"]
    problems = []
    for vid, inputs in sorted(hashes.items()):
        name = f"{vid}.png"
        entry = entries.get(vid)
        if entry is None:
            problems.append(f"view '{vid}' has no entry in {LOCK}")
        elif entry.inputs != inputs:
            problems.append(f"view '{vid}' changed since its image was rendered")
        if name not in images:
            problems.append(f"view '{vid}': {VIEWS / name} is missing")
        elif entry is not None:
            try:
                actual = entry_for(entry.inputs, images[name])
            except ViewsError as err:
                problems.append(f"view '{vid}': {VIEWS / name}: {err}")
                continue
            if actual.png != entry.png:
                problems.append(f"view '{vid}': {VIEWS / name} is not the image in {LOCK} "
                                "(sha256 differs)")
            elif (actual.width, actual.height) != (entry.width, entry.height):
                problems.append(f"view '{vid}': {VIEWS / name} is {actual.width}x{actual.height}"
                                f", {LOCK} says {entry.width}x{entry.height}")
    problems += [f"{LOCK} lists '{vid}', which is not a view of the model"
                 for vid in sorted(entries) if vid not in hashes]
    problems += [f"{VIEWS / name} belongs to no view of the model"
                 for name in sorted(images) if name not in {f"{vid}.png" for vid in hashes}]
    if not problems and lock != format_lock(entries):
        problems.append(f"{VIEWS / LOCK} is not in its generated form (header, order, spacing)")
    return [f"{p}; {FIX}" for p in problems]


def update(hashes: dict[str, str], views: Path, rendered: Path) -> list[str]:
    """Bring the views folder in step with the model; return what changed (empty: nothing).

    A view keeps its committed image when its lock entry is current (same input hash, and the
    file has the locked sha256 and size); otherwise the freshly rendered PNG replaces it. Images
    and entries of views no longer in the model, and any other file in the folder, are removed.
    """
    views.mkdir(parents=True, exist_ok=True)
    lock_file = views / LOCK
    old_text = lock_file.read_text(encoding="utf-8") if lock_file.exists() else ""
    try:
        old = parse_lock(old_text)
    except ViewsError:
        old = {}
    entries, changes = {}, []
    for vid, inputs in sorted(hashes.items()):
        target = views / f"{vid}.png"
        entry = old.get(vid)
        if entry is not None and entry.inputs == inputs and target.is_file():
            try:
                if entry_for(inputs, target.read_bytes()) == entry:
                    entries[vid] = entry
                    continue
            except ViewsError:
                pass
        source = rendered / f"{vid}.png"
        if not source.is_file():
            raise ViewsError(f"Archi rendered no image for view '{vid}' (no {source})")
        entries[vid] = entry_for(inputs, source.read_bytes())
        shutil.copyfile(source, target)
        changes.append(f"rendered {target}")
    keep = {LOCK} | {f"{vid}.png" for vid in entries}
    for stray in sorted(views.iterdir()):
        if stray.name not in keep:
            stray.unlink()
            changes.append(f"removed {stray}")
    new_text = format_lock(entries)
    if new_text != old_text:
        lock_file.write_text(new_text, encoding="utf-8")
        changes.append(f"wrote {lock_file}")
    return changes


def dims(lock: str, rendered: Path) -> tuple[list[str], list[str]]:
    """(one report line per view, problems): rendered size against the locked size."""
    lines, problems = [], []
    for vid, entry in sorted(parse_lock(lock).items()):
        try:
            width, height = png_size((rendered / f"{vid}.png").read_bytes())
        except (OSError, ViewsError) as err:
            problems.append(f"view '{vid}': no rendered image to compare: {err}")
            continue
        same = (width, height) == (entry.width, entry.height)
        lines.append(f"{vid}: rendered {width}x{height}, lock {entry.width}x{entry.height}"
                     f" {'equal' if same else 'DIFFERENT'}")
        if not same:
            problems.append(f"view '{vid}': rendered {width}x{height} here, but {LOCK} says "
                            f"{entry.width}x{entry.height}")
    return lines, problems


# --- command line -------------------------------------------------------------------------------

def _images(views: Path) -> dict[str, bytes]:
    if not views.is_dir():
        return {}
    return {p.name: p.read_bytes() for p in sorted(views.iterdir()) if p.name != LOCK}


def main(argv: list[str]) -> int:
    mode, args = (argv[0], argv[1:]) if argv else ("", [])
    if not ((mode == "--check" and len(args) <= 1)
            or (mode in ("--update", "--dims") and len(args) == 2)):
        print(__doc__, file=sys.stderr)
        return 2
    root = Path(args[0]) if args else ROOT
    views = root / VIEWS
    try:
        version = xsd_check.read_env(root / ENV)["ARCHI_VERSION"]
        model = (root / MODEL).read_bytes()
        hashes = input_hashes(model, version)
    except (OSError, KeyError, exchange.FormatError) as err:
        print(f"views: cannot read the model or the Archi version: {err}", file=sys.stderr)
        return 1
    lock_file = views / LOCK
    if mode == "--check":
        lock = lock_file.read_text(encoding="utf-8") if lock_file.is_file() else None
        problems = check(hashes, lock, _images(views))
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        if not problems:
            print(f"views: {len(hashes)} images and {LOCK} match the model")
        return 1 if problems else 0
    rendered = Path(args[1]) / exchange.read(model).identifier / "images"
    try:
        if mode == "--update":
            for change in update(hashes, views, rendered):
                print(f"views: {change}")
            return 0
        lines, problems = dims(lock_file.read_text(encoding="utf-8"), rendered)
    except (OSError, ViewsError) as err:
        print(f"views: {err}", file=sys.stderr)
        return 1
    for line in lines:
        print(line)
    for problem in problems:
        print(f"  - {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
